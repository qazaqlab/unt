// Generate all 140 daily plans dynamically from the 20 weeks
(function generate140Days() {
  const days = [];
  const dayNames = ["Дүйсенбі", "Сейсенбі", "Сәрсенбі", "Бейсенбі", "Жұма", "Сенбі", "Жексенбі"];
  for (let w = 0; w < 20; w++) {
    const wk = window.UBT_CURRICULUM.weeks[w];
    for (let d = 0; d < 7; d++) {
      const dayNumber = w * 7 + d + 1;
      const isWeekend = d >= 5;
      const physCode = wk.phys[d % wk.phys.length];
      const mathCode = wk.math[d % wk.math.length];
      const histCode = wk.hist[d % wk.hist.length];
      const mslCode  = wk.msl[d % wk.msl.length];

      let focusTitle = "";
      let primarySubject = "phys";
      if (d === 0 || d === 2) {
        primarySubject = "phys";
        focusTitle = `Физика басымдығы (${physCode}) + Қазақстан тарихы (${histCode})`;
      } else if (d === 1 || d === 3) {
        primarySubject = "math";
        focusTitle = `Математика басымдығы (${mathCode}) + Мат. сауаттылық (${mslCode})`;
      } else if (d === 4) {
        primarySubject = "phys";
        focusTitle = `Қос бейінді синтез: Физика (${physCode}) + Математика (${mathCode})`;
      } else if (d === 5) {
        primarySubject = "exam";
        focusTitle = (w + 1) % 4 === 0
          ? `🏆 АЙЛЫҚ ТОЛЫҚ ҰБТ СИМУЛЯЦИЯСЫ (130 БАЛЛ / 240 МИНУТ)`
          : `📝 ${w + 1}-Апталық бақылау тесті + С-бөлім есептерін талдау`;
      } else {
        primarySubject = "review";
        focusTitle = `🔄 Анти-Выгорание & Spaced Repetition (1-3-7-21 Қатемен жұмыс + Жеңіл қайталау)`;
      }

      days.push({
        day: dayNumber,
        week: w + 1,
        month: wk.month,
        dayOfWeekName: dayNames[d],
        isWeekend,
        primarySubject,
        title: `${dayNumber}-күн (${dayNames[d]}): ${focusTitle}`,
        topics: { phys: physCode, math: mathCode, hist: histCode, msl: mslCode },
        blocks: isWeekend
          ? window.UBT_CURRICULUM.meta.dailyScheduleTemplate.weekend
          : window.UBT_CURRICULUM.meta.dailyScheduleTemplate.weekday
      });
    }
  }
  window.UBT_CURRICULUM.days = days;
})();
